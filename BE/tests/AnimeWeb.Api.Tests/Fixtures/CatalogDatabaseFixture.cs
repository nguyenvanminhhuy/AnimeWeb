using AnimeWeb.Api.Infrastructure.Persistence;
using AnimeWeb.Api.Infrastructure.Persistence.Seeding;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.Extensions.DependencyInjection;
using Npgsql;

namespace AnimeWeb.Api.Tests.Fixtures;

public sealed class CatalogDatabaseFixture : IAsyncLifetime
{
    private readonly string schema = "catalog_" + Guid.NewGuid().ToString("N");
    private string? rootConnectionString;
    private bool schemaCreated;
    public ApiFactory Factory { get; private set; } = null!;
    public HttpClient Client { get; private set; } = null!;
    public ManualTimeProvider Clock { get; } = new();

    public async Task InitializeAsync()
    {
        var candidate = Environment.GetEnvironmentVariable("ANIMEWEB_TEST_DATABASE");
        if (string.IsNullOrWhiteSpace(candidate))
        {
            return;
        }
        var parsed = new NpgsqlConnectionStringBuilder(candidate);
        Assert.Equal("127.0.0.1", parsed.Host);
        Assert.Equal(54330, parsed.Port);
        Assert.Equal("animeweb_test", parsed.Database);
        Assert.Equal("animeweb_test", parsed.Username);
        rootConnectionString = candidate;
        await using var connection = new NpgsqlConnection(rootConnectionString);
        await connection.OpenAsync();
        await using var create = new NpgsqlCommand($"CREATE SCHEMA \"{schema}\"", connection);
        await create.ExecuteNonQueryAsync();
        schemaCreated = true;

        parsed.SearchPath = schema;
        Factory = new ApiFactory(parsed.ConnectionString, clock: Clock);
        Client = Factory.CreateClient();
        await using var scope = Factory.Services.CreateAsyncScope();
        var database = scope.ServiceProvider.GetRequiredService<AnimeWebDbContext>();
        // Exercise upgrade from the existing infrastructure migration, not only fresh creation.
        var baseline = database.Database.GetMigrations().First();
        await database.GetService<IMigrator>().MigrateAsync(baseline);
        Assert.Single(await database.Database.GetAppliedMigrationsAsync());
        var catalogMigration = database.Database.GetMigrations().Single(migration => migration.EndsWith("_InitialCatalog"));
        await database.GetService<IMigrator>().MigrateAsync(catalogMigration);
        // Insert using the old wire-independent schema, before the new Version/Subtitle columns exist.
        await database.Database.ExecuteSqlRawAsync("""
            INSERT INTO "Anime" ("Id","Slug","Title","AlternativeTitles","Synopsis","PosterUrl","Status","Format","ReleaseYear","PublicationStatus")
            VALUES ('upgrade_fixture','upgrade-fixture','Existing catalog',ARRAY[]::text[],'Preserved synopsis','/fixture.webp','upcoming','tv',2026,'published')
            """);
        await database.Database.MigrateAsync();
        Assert.Equal(7, (await database.Database.GetAppliedMigrationsAsync()).Count());
        var upgraded = await database.Anime.SingleAsync(x => x.Id == "upgrade_fixture");
        Assert.Equal("Preserved synopsis", upgraded.Synopsis);
        Assert.Equal(1, upgraded.Version);
        Assert.Equal("", upgraded.Subtitle);
        database.Remove(upgraded);
        await database.SaveChangesAsync();
        Assert.True(await CatalogDemoSeeder.SeedAsync(database));
        Assert.False(await CatalogDemoSeeder.SeedAsync(database));
        Assert.Equal(7, await database.Anime.CountAsync());
    }

    public async Task DisposeAsync()
    {
        if (Factory is not null)
        {
            Client.Dispose();
            await Factory.DisposeAsync();
        }
        if (schemaCreated && !string.IsNullOrWhiteSpace(rootConnectionString))
        {
            // The schema is generated by this fixture; never drop public or an input-provided schema.
            Assert.Matches("^catalog_[a-f0-9]{32}$", schema);
            await using var connection = new NpgsqlConnection(rootConnectionString);
            await connection.OpenAsync();
            await using var drop = new NpgsqlCommand($"DROP SCHEMA IF EXISTS \"{schema}\" CASCADE", connection);
            await drop.ExecuteNonQueryAsync();
        }
    }
}
